package net.frozenblock.thecopperierage.mixin.block.gearbox;

import net.frozenblock.thecopperierage.block.gearbox.GearboxRotationSessionInterface;
import net.minecraft.world.entity.vehicle.minecart.AbstractMinecart;
import net.minecraft.world.entity.vehicle.minecart.MinecartBehavior;
import net.minecraft.world.entity.vehicle.minecart.NewMinecartBehavior;
import org.spongepowered.asm.mixin.Final;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.Shadow;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

@Mixin(AbstractMinecart.class)
public abstract class AbstractMinecartMixin implements GearboxRotationSessionInterface {

	@Shadow
	@Final
	private MinecartBehavior behavior;

	@Inject(method = "tick", at = @At("TAIL"))
	private void theCopperierAge$rotateMinecartFromUpFacingGearbox(CallbackInfo info) {
		this.theCopperierAge$tickRotationSession(this.behavior instanceof NewMinecartBehavior);
	}
}
