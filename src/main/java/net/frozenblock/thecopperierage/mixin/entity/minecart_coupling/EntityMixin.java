package net.frozenblock.thecopperierage.mixin.entity.minecart_coupling;

import net.frozenblock.thecopperierage.entity.coupling.MinecartCouplingUtil;
import net.minecraft.world.entity.Entity;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

@Mixin(Entity.class)
public class EntityMixin {

	@Inject(method = "onRemoval", at = @At("HEAD"))
	public void theCopperierAge$dropCouplingOnRemoval(Entity.RemovalReason removalReason, CallbackInfo info) {
		MinecartCouplingUtil.uncoupleTo(Entity.class.cast(this), true);
	}
}
